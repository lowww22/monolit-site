export type ProductKind = 'beton' | 'rastvor';

export function getProduct(kind: ProductKind, slug: string) {
  const list = kind === 'beton' ? concrete : mortar;
  return list.find((p) => p.slug === slug);
}

export function productUrl(kind: ProductKind, slug: string) {
  return `/${kind}/${slug}`;
}

export function productTitle(kind: ProductKind, p: Product) {
  return kind === 'beton' ? `Бетон ${p.mark}` : `Раствор ${p.mark}`;
}

/** Все адреса товарных страниц — для sitemap.xml */
export const productPaths = [
  ...concrete.map((p) => productUrl('beton', p.slug)),
  ...mortar.map((p) => productUrl('rastvor', p.slug)),
];
